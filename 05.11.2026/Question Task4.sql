SELECT DEPARTMENT, SUM(SALARY) AS TOTAL_SALARY FROM Worker GROUP BY DEPARTMENT ORDER BY TOTAL_SALARY DESC;

SELECT DEPARTMENT, AVG(SALARY) AS AVERAGE_SALARY FROM Worker GROUP BY DEPARTMENT ORDER BY AVERAGE_SALARY ASC;

SELECT DEPARTMENT, COUNT(*) AS TOTAL_WORKERS FROM Worker ORDER BY TOTAL_WORKERS DESC;

SELECT DEPARTMENT, MIN(SALARY) AS MINIMUM_SALARY FROM Worker GROUP BY DEPARTMENT ORDER BY MINIMUM_SALARY ASC;

SELECT DEPARTMENT, COUNT(*) AS TOTAL_WORKERS, MAX(SALARY) AS MAX_SALARY,MIN(SALARY) AS MIN_SALARY FROM Worker GROUP BY DEPARTMENT;

SELECT DEPARTMENT, SUM(SALARY) AS TOTAL_SALARY, AVG(SALARY) AS AVERAGE_SALARY FROM Worker GROUP BY DEPARTMENT;

